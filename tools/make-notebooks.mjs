import fs from 'fs';
import path from 'path';

const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname).replace(/^\/([A-Za-z]:)/, '$1'), '..');
const OUT = path.join(REPO, 'notebooks');
fs.mkdirSync(OUT, { recursive: true });

const md = (...lines) => ({ cell_type: 'markdown', metadata: {}, source: join(lines) });
const code = (...lines) => ({ cell_type: 'code', execution_count: null, metadata: {}, outputs: [], source: join(lines) });

/** nbformat wants an array of lines, each keeping its trailing newline bar the last. */
function join(lines) {
  const text = lines.join('\n');
  const parts = text.split('\n');
  return parts.map((l, i) => (i === parts.length - 1 ? l : l + '\n'));
}

function notebook(cells) {
  return {
    cells,
    metadata: {
      kernelspec: { display_name: 'Python 3', language: 'python', name: 'python3' },
      language_info: { name: 'python', pygments_lexer: 'ipython3' },
    },
    nbformat: 4,
    nbformat_minor: 5,
  };
}

